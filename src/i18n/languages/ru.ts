/** 1, 21, 31 … секунда; 2–4, 22–24 … секунды; otherwise (and 11–14) секунд */
const seconds = (n: number) => {
  const one = n % 10 === 1 && n % 100 !== 11
  const few = n % 10 >= 2 && n % 10 <= 4 && !(n % 100 >= 12 && n % 100 <= 14)
  return `${n} ${one ? 'секунда' : few ? 'секунды' : 'секунд'}`
}

